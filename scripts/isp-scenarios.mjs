// Builds src/isp-scenarios/data/isp-2026.json: the National Electricity Market's annual
// generation (TWh) and capacity (GW) by technology, history and then AEMO's 2026 Integrated
// System Plan projections to 2050, for the ISP's three scenarios. Run it by hand from the repo
// root (`node scripts/isp-scenarios.mjs`) when a new ISP comes out, every two years; the site
// never runs it. Node 18 or later, no npm dependencies. `--cache <dir>` keeps the downloads.
//
// The projections are AEMO's generation and storage outlook workbooks for the 2026 ISP (final,
// 25 June 2026), https://aemo.com.au/energy-systems/major-publications/integrated-system-plan-isp/2026-integrated-system-plan-isp,
// as parsed by Open Electricity for its Scenario Explorer (https://openelectricity.org.au/scenarios)
// and published in its open-source frontend, github.com/opennem/openelectricity (MIT), at
// static/data/scenarios/2026_ISP_final/<scenario>.json: per fuel technology, scenario,
// candidate development path and region, energy in GWh and capacity in MW for the financial
// years ending 2027 to 2050. AEMO's own page sits behind a bot challenge, so the workbooks
// cannot be fetched by a script; these files are the same numbers. The optimal development
// path, CDP4, is taken for every scenario, and the NEM as a whole (`_all`).
//
// The history is Open Electricity's monthly record of generation by fuel technology
// (data.openelectricity.org.au/v4/stats/au/NEM/energy/all.json), summed into financial years
// (July to June) from the year ending 2010 to the last complete one, and its annual capacity
// file (data.openelectricity.org.au/capacity/unified_annual_capacity.json), which runs to the
// year ending 2024 and has not been refreshed since, so the capacity view has a gap of two
// years before the projection begins.
//
// Technologies are grouped as AEMO's Figure 2 groups them: black coal, brown coal, gas (all
// turbines, with carbon capture, and distillate), hydro, bioenergy, onshore and offshore wind,
// utility and rooftop solar, and storage (grid, distributed and VPP batteries). Storage is
// kept out of the generation stack, as AEMO's figure keeps it (its discharge is energy
// generated by the others earlier), and in the capacity stack. Imports and exports cancel
// across the NEM and are left out, as is demand response (nothing in these runs).
//
// Output: `techs` (id, label, colour), `scenarios` (id, label, AEMO's likelihood weight),
// `history` {generation: {years, values: {tech: TWh}}, capacity: {years, values: {tech: GW}}}
// and `projections` {scenario: {years, generation, capacity}} on the same layout.

import {mkdirSync, readFileSync, writeFileSync, existsSync} from "node:fs";
import {dirname, join} from "node:path";
import {fileURLToPath} from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(ROOT, "src/isp-scenarios/data/isp-2026.json");

const RELEASE = "2026_ISP_final";
const OE_SCENARIOS = `https://raw.githubusercontent.com/opennem/openelectricity/main/static/data/scenarios/${RELEASE}`;
const HISTORY = "https://data.openelectricity.org.au/v4/stats/au/NEM/energy/all.json";
const CAPACITY = "https://data.openelectricity.org.au/capacity/unified_annual_capacity.json";
const PATHWAY = "CDP4 (ODP)";
const FIRST_FY = 2010;

const cacheArg = process.argv.indexOf("--cache");
const CACHE = cacheArg > 0 ? process.argv[cacheArg + 1] : null;

// AEMO's three scenarios and the likelihood weights it gave them (2026 ISP, executive summary).
const SCENARIOS = [
  {id: "step_change", label: "Step Change", likelihood: 0.46,
    description: "AEMO's most likely scenario: the transition continues at the pace needed to meet Australia's emissions targets."},
  {id: "accelerated_transition", label: "Accelerated Transition", likelihood: 0.27,
    description: "Faster electrification and renewable build-out, with demand and investment running ahead of Step Change."},
  {id: "slower_growth", label: "Slower Growth", likelihood: 0.27,
    description: "Weaker economic growth and slower electrification, so less new demand and a slower build."},
];

// The technology groups, in stacking order from the bottom, in Okabe and Ito's colours (coal
// black, with brown coal a lighter shade of it; gas orange; bioenergy vermilion; hydro sky
// blue; wind bluish green, darker onshore and lighter offshore; solar yellow, utility as it
// is and rooftop lighter; storage blue), and which of the source's fuel technologies each
// gathers in the history and the projections.
const TECHS = [
  {id: "coal_black", label: "Coal (black)", colour: "#000000",
    history: ["coal_black"], projection: ["coal_black"]},
  {id: "coal_brown", label: "Coal (brown)", colour: "#4D4D4D",
    history: ["coal_brown"], projection: ["coal_brown"]},
  {id: "gas", label: "Gas (and distillate)", colour: "#E69F00",
    history: ["gas_ccgt", "gas_ocgt", "gas_steam", "gas_recip", "gas_wcmg", "distillate"],
    projection: ["gas_ccgt", "gas_ccgt_ccs", "gas_ocgt"]},
  {id: "bioenergy", label: "Bioenergy", colour: "#D55E00",
    history: ["bioenergy_biomass", "bioenergy_biogas"], projection: ["bioenergy"]},
  {id: "hydro", label: "Hydro", colour: "#56B4E9",
    history: ["hydro"], projection: ["hydro"]},
  {id: "wind", label: "Wind (onshore)", colour: "#007E5C",
    history: ["wind"], projection: ["wind"]},
  {id: "wind_offshore", label: "Wind (offshore)", colour: "#59C0A4",
    history: [], projection: ["wind_offshore"]},
  {id: "solar_utility", label: "Solar (utility)", colour: "#F0E442",
    history: ["solar_utility"], projection: ["solar_utility"]},
  {id: "solar_rooftop", label: "Solar (rooftop)", colour: "#F7F097",
    history: ["solar_rooftop"], projection: ["solar_rooftop"]},
  {id: "storage", label: "Storage (batteries)", colour: "#0072B2", storage: true,
    history: ["battery_discharging"], historyCapacity: ["battery"],
    projection: ["battery_discharging", "battery_VPP_discharging", "battery_distributed_discharging"],
    projectionCapacity: ["battery", "battery_VPP", "battery_distributed"]},
];

async function fetchJson(url) {
  const file = CACHE && join(CACHE, url.replace(/^https?:\/\//, "").replace(/[^\w.-]+/g, "_") + ".json");
  if (file && existsSync(file)) return JSON.parse(readFileSync(file, "utf8"));
  const res = await fetch(url, {headers: {accept: "application/json"}});
  if (!res.ok) throw new Error(`${res.status} ${res.statusText} for ${url}`);
  const json = await res.json();
  if (file) { mkdirSync(dirname(file), {recursive: true}); writeFileSync(file, JSON.stringify(json)); }
  return json;
}

const round = (v, d) => Math.round(v * 10 ** d) / 10 ** d;
const monthIndex = iso => Number(iso.slice(0, 4)) * 12 + Number(iso.slice(5, 7)) - 1;

// Financial-year sums of the monthly history, in TWh, for the years ending FIRST_FY to the
// last year with all twelve months. A technology's months before its record begins count
// as nothing.
function historyGeneration(stats) {
  const series = stats.data.filter(s => s.type === "energy" && s.fuel_tech);
  const lastMonth = Math.max(...series.map(s => monthIndex(s.history.last)));
  // The last complete financial year ends in the June at or before the last month.
  const lastFY = Math.floor(lastMonth / 12) - (lastMonth % 12 >= 5 ? 0 : 1);
  const years = [];
  for (let fy = FIRST_FY; fy <= lastFY; fy++) years.push(fy);
  const byFuel = new Map(series.map(s => [s.fuel_tech, s]));
  const values = {};
  for (const t of TECHS) {
    values[t.id] = years.map(fy => {
      const from = monthIndex(`${fy - 1}-07`), to = monthIndex(`${fy}-06`);
      let sum = 0;
      for (const ft of t.history) {
        const s = byFuel.get(ft);
        if (!s) continue;
        const i0 = monthIndex(s.history.start);
        for (let m = from; m <= to; m++) {
          const v = s.history.data[m - i0];
          if (v !== null && v !== undefined) sum += v;
        }
      }
      return round(sum / 1000, 2);   // GWh → TWh
    });
  }
  return {years, values};
}

// The NEM-wide annual capacity history, in GW, for the years the file covers in full.
function historyCapacity(cap) {
  const series = cap.data.filter(s => s.network === "nem" && !s.region && s.fuel_tech);
  const byFuel = new Map(series.map(s => [s.fuel_tech, s]));
  const any = series[0];
  const firstFY = Number(any.history.start.slice(0, 4)) + 1;   // "1999-07-01" begins the year ending 2000
  const n = any.history.data.length - 1;                        // the last point is the running year
  const years = [];
  for (let i = 0; i < n; i++) if (firstFY + i >= FIRST_FY) years.push(firstFY + i);
  const values = {};
  for (const t of TECHS) {
    const fts = t.historyCapacity ?? t.history;
    values[t.id] = years.map(fy => {
      let sum = 0;
      for (const ft of fts) {
        const s = byFuel.get(ft);
        const v = s?.history.data[fy - firstFY];
        if (v) sum += v;
      }
      return round(sum / 1000, 3);   // MW → GW
    });
  }
  return {years, values};
}

// One scenario's projection: the ODP, the NEM as a whole, by financial year ending.
function projection(file, scenarioId) {
  const rows = file.data.filter(d => d.scenario === scenarioId && d.pathway === PATHWAY && d.region === "_all");
  if (!rows.length) throw new Error(`no ${PATHWAY} rows for ${scenarioId}`);
  const sample = rows[0].projection;
  const firstFY = Number(sample.start.slice(0, 4)) + 1;   // "2026-07-01" begins the year ending 2027
  const years = sample.data.map((_, i) => firstFY + i);
  const gather = (type, key, scale, digits) => {
    const values = {};
    for (const t of TECHS) {
      const fts = t[key] ?? t.projection;
      const sum = new Array(years.length).fill(0);
      for (const r of rows) {
        if (r.type !== type || !fts.includes(r.fuel_tech)) continue;
        r.projection.data.forEach((v, i) => { sum[i] += v ?? 0; });
      }
      values[t.id] = sum.map(v => round(v / scale, digits));
    }
    return values;
  };
  return {years, generation: gather("energy", "projection", 1000, 2), capacity: gather("capacity", "projectionCapacity", 1000, 3)};
}

async function main() {
  const [stats, cap] = await Promise.all([fetchJson(HISTORY), fetchJson(CAPACITY)]);
  const generation = historyGeneration(stats);
  const capacity = historyCapacity(cap);
  console.log(`history: generation FY${generation.years[0]}–FY${generation.years.at(-1)}, capacity FY${capacity.years[0]}–FY${capacity.years.at(-1)}`);

  const projections = {};
  let createdAt = null;
  for (const s of SCENARIOS) {
    const file = await fetchJson(`${OE_SCENARIOS}/${s.id}.json`);
    createdAt ??= file.created_at;
    if (file.release && file.release !== RELEASE) throw new Error(`unexpected release ${file.release}`);
    projections[s.id] = projection(file, s.id);
    const g = projections[s.id].generation;
    const total = fy => TECHS.filter(t => !t.storage).reduce((sum, t) => sum + g[t.id][projections[s.id].years.indexOf(fy)], 0);
    console.log(`${s.label}: FY${projections[s.id].years[0]}–FY${projections[s.id].years.at(-1)}, generation ${total(2030).toFixed(0)} TWh in FY2030, ${total(2050).toFixed(0)} TWh in FY2050`);
  }

  const out = {
    generated: new Date().toISOString().slice(0, 10),
    release: RELEASE,
    pathway: PATHWAY,
    source: {
      name: "AEMO (2026), 2026 Integrated System Plan for the National Electricity Market",
      url: "https://aemo.com.au/energy-systems/major-publications/integrated-system-plan-isp/2026-integrated-system-plan-isp",
      pdf: "https://aemo.com.au/-/media/files/major-publications/isp/2026/2026-integrated-system-plan-isp.pdf",
      via: "Open Electricity Scenario Explorer",
      viaUrl: "https://openelectricity.org.au/scenarios",
      viaFiles: OE_SCENARIOS,
      viaCreatedAt: createdAt,
      history: HISTORY,
      capacityHistory: CAPACITY,
      licence: "Open Electricity data CC BY-NC 4.0",
    },
    techs: TECHS.map(({id, label, colour, storage}) => ({id, label, colour, ...(storage ? {storage: true} : {})})),
    scenarios: SCENARIOS,
    history: {generation, capacity},
    projections,
  };
  mkdirSync(dirname(OUT), {recursive: true});
  writeFileSync(OUT, JSON.stringify(out));
  console.log(`wrote ${OUT} (${Math.round(JSON.stringify(out).length / 1024)} KB)`);
}

main().catch(e => { console.error(e); process.exit(1); });
